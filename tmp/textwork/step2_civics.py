def main():
    with io.open(PATH, encoding='utf-8') as f:
        text = f.read()
    data = json.loads(text)
    civics = {c['id']: c for c in data['civics']}
    missing, notfound = [], []
    for cid, (desc, hist) in TEXTS.items():
        if cid not in civics:
            missing.append(cid); continue
        old_d = f'"description": "{civics[cid]["description"]}"'
        old_h = f'"history": "{civics[cid]["history"]}"'
        if old_d not in text:
            notfound.append(f'{cid}.description'); continue
        text = text.replace(old_d, f'"description": "{desc}"')
        if old_h not in text:
            notfound.append(f'{cid}.history'); continue
        text = text.replace(old_h, f'"history": "{hist}"')
    json.loads(text)
    with io.open(PATH, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'OK 写入完成。缺失id={missing} 未找到={notfound}')

if __name__ == '__main__':
    main()
