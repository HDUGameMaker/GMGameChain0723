def main():
    with io.open(PATH, encoding='utf-8') as f:
        text = f.read()
    data = json.loads(text)  # 校验可解析
    techs = {t['id']: t for t in data['techs']}
    missing, notfound = [], []
    for tid, (desc, hist) in TEXTS.items():
        if tid not in techs:
            missing.append(tid); continue
        old_d = f'"description": "{techs[tid]["description"]}"'
        old_h = f'"history": "{techs[tid]["history"]}"'
        new_d = f'"description": "{desc}"'
        new_h = f'"history": "{hist}"'
        # 按 id 锚点 + 字段名定位（每个条目内唯一）
        # 直接全文替换旧文本（旧文本因含名称而唯一）
        if old_d not in text:
            notfound.append(f'{tid}.description'); continue
        text = text.replace(old_d, new_d)
        if old_h not in text:
            notfound.append(f'{tid}.history'); continue
        text = text.replace(old_h, new_h)
    # 再次校验
    json.loads(text)
    with io.open(PATH, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'OK 写入完成。缺失id={missing} 未找到={notfound}')

if __name__ == '__main__':
    main()
